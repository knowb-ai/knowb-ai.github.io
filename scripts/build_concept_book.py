#!/usr/bin/env python3
"""Build the Org Book concept-book plates from the design canvas boards.

Each board in design/concept-book/*.dc.html is a self-contained design-canvas
artboard. This script turns every board into a Zola partial under
templates/concept/ and writes one stylesheet, static/css/concept-book.css, with
each board's styles scoped to that board so plates never leak into the site.

Run from anywhere:  python3 scripts/build_concept_book.py
"""

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "design" / "concept-book"
PARTIALS = ROOT / "templates" / "concept"
STYLESHEET = ROOT / "static" / "css" / "concept-book.css"
PREFIX = "cb-"

X_DC = re.compile(r"<x-dc>(.*)</x-dc>", re.S)
HELMET = re.compile(r"<helmet>(.*?)</helmet>", re.S)
STYLE = re.compile(r"<style>(.*?)</style>", re.S)
CLASS_ATTR = re.compile(r'class="([^"]*)"')
HEADING = re.compile(r"<(/?)h[1-6]\b")
CLASS_SELECTOR = re.compile(r"\.([A-Za-z_][\w-]*)")


def slug(path):
    return re.sub(r"(?<!^)(?=[A-Z])", "-", path.name.split(".")[0]).lower()


def scope_css(css, scope):
    """Prefix every class selector and scope each rule to its board."""
    rules = []
    for chunk in css.split("}"):
        if "{" not in chunk:
            continue
        selectors, declarations = chunk.split("{", 1)
        scoped = []
        for selector in selectors.split(","):
            selector = selector.strip()
            if not selector or selector == "body":
                continue
            selector = CLASS_SELECTOR.sub(lambda m: "." + PREFIX + m.group(1), selector)
            scoped.append(f"{scope} {selector}")
        if scoped:
            rules.append(",".join(scoped) + "{" + declarations.strip() + "}")
    return "\n".join(rules)


def build_board(path):
    html = path.read_text(encoding="utf-8")
    body = X_DC.search(html).group(1)
    helmet = HELMET.search(body)
    css = "\n".join(STYLE.findall(helmet.group(1))) if helmet else ""
    markup = HELMET.sub("", body).strip()
    markup = CLASS_ATTR.sub(
        lambda m: 'class="' + " ".join(PREFIX + c for c in m.group(1).split()) + '"', markup
    )
    # Plates are pictures of a design: demote headings so they stay out of the page outline.
    markup = HEADING.sub(lambda m: f"<{m.group(1)}p", markup)
    name = slug(path)
    partial = (
        f"{{# Generated by scripts/build_concept_book.py from design/concept-book/{path.name}. Do not edit. #}}\n"
        f'<div class="cb-board cb-board--{name}" inert>\n{markup}\n</div>\n'
    )
    (PARTIALS / f"{name}.html").write_text(partial, encoding="utf-8")
    return f"/* {path.name} */\n" + scope_css(css, f".cb-board--{name}")


def main():
    PARTIALS.mkdir(parents=True, exist_ok=True)
    sheets = [build_board(path) for path in sorted(SOURCE.glob("*.dc.html"))]
    header = (
        "/* Generated by scripts/build_concept_book.py from design/concept-book/. Do not edit. */\n"
        ".cb-board a{text-decoration:none}\n"
    )
    STYLESHEET.write_text(header + "\n".join(sheets) + "\n", encoding="utf-8")
    print(f"Built {len(sheets)} plates into {PARTIALS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
