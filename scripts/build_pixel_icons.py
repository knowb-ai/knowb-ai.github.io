#!/usr/bin/env python3
"""Build the pixel icon macro from the KnowB pixel icon dictionary.

Reads design/pixel-icons/dictionary.txt (8x8 maps, see its header) and writes
templates/pixel_icons.html with one `pixel_icon` macro. Each row is drawn as
horizontal runs, so an icon stays a handful of crisp rects.

Run from anywhere:  python3 scripts/build_pixel_icons.py
"""

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
DICTIONARY = ROOT / "design" / "pixel-icons" / "dictionary.txt"
MACRO = ROOT / "templates" / "pixel_icons.html"
SIZE = 8
FILLS = {"#": "{{ color }}", "o": "{{ cut }}"}
ENTRY = re.compile(r"^([a-z][a-z0-9-]*):\s*(.+)$")


def parse(text):
    icons, name, rows = [], None, []
    for line in text.splitlines():
        line = line.strip()
        # Comments start with "#" and contain a space; map rows never do.
        if not line or (line.startswith("#") and (line == "#" or " " in line)):
            continue
        entry = ENTRY.match(line)
        if entry:
            name, rows = entry.group(1), []
            icons.append((name, entry.group(2), rows))
            continue
        if name is None or len(line) != SIZE or set(line) - set(".#o"):
            raise SystemExit(f"bad row {line!r} in {name or 'header'}")
        rows.append(line)
    for name, _, rows in icons:
        if len(rows) != SIZE:
            raise SystemExit(f"{name}: expected {SIZE} rows, got {len(rows)}")
    return icons


def rects(rows):
    out = []
    for y, row in enumerate(rows):
        x = 0
        while x < SIZE:
            mark = row[x]
            end = x
            while end < SIZE and row[end] == mark:
                end += 1
            if mark in FILLS:
                out.append(f'<rect x="{x}" y="{y}" width="{end - x}" height="1" fill="{FILLS[mark]}"/>')
            x = end
    return "".join(out)


def main():
    icons = parse(DICTIONARY.read_text(encoding="utf-8"))
    branches = []
    for index, (name, meaning, rows) in enumerate(icons):
        keyword = "if" if index == 0 else "elif"
        branches.append(f'{{%- {keyword} name == "{name}" -%}}{{# {meaning} #}}\n{rects(rows)}')
    macro = (
        "{# Generated by scripts/build_pixel_icons.py from design/pixel-icons/dictionary.txt. Do not edit. #}\n"
        '{% macro pixel_icon(name, color="#F59A52", cut="#1D1514", size=28) %}\n'
        '<svg class="pixel-icon" width="{{ size }}" height="{{ size }}" viewBox="0 0 8 8" aria-hidden="true">\n'
        + "\n".join(branches)
        + "\n{%- endif -%}\n</svg>\n{%- endmacro pixel_icon %}\n"
    )
    MACRO.write_text(macro, encoding="utf-8")
    print(f"Built {len(icons)} pixel icons into {MACRO.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
